// Actual AES-GCM + PBKDF2 unit test for V4 vault, using Node WebCrypto.
import fs from 'node:fs';
import vm from 'node:vm';
import {webcrypto} from 'node:crypto';
import assert from 'node:assert/strict';
const html=fs.readFileSync(new URL('./index.html',import.meta.url),'utf8');
const script=html.match(/<script>([\s\S]*?)<\/script>/)[1];
const pure=script.slice(0,script.indexOf('(() => {'));
const storage=new Map();
const localStorage={getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,v),removeItem:k=>storage.delete(k)};
const ctx=vm.createContext({window:{localStorage},crypto:webcrypto,TextEncoder,TextDecoder,atob,btoa,structuredClone,Uint8Array,ArrayBuffer,Date,console});
vm.runInContext(pure,ctx);
const EncryptedVault=vm.runInContext('EncryptedVault',ctx);
const e=new EncryptedVault(localStorage);
await e.create('unit-test-secret-passphrase');
await e.ensureBuyer('JulianR9423');
await e.addIncoming('julianr9423','First private message');
await e.markSent('JulianR9423','A reply');
await e.ensureBuyer('NewBuyer123');
await e.addIncoming('NewBuyer123','Second buyer message');
assert.equal(e.list().length,2);
assert.equal(e.getBuyer('JulianR9423').displayName,'JulianR9423');
assert.equal(e.getBuyer('JulianR9423').events.length,2);
assert.equal(e.getBuyer('NewBuyer123').events.length,1);
await e.setReferences([{id:'private-1',title:'My voice',kind:'voice',enabled:true,text:'Private voice samples'}]);
await e.setBuyerSettings('JulianR9423',{personality:'spicy',smartSelect:true,profanity:'strong'});
await e.setBuyerSettings('NewBuyer123',{personality:'sweet',smartSelect:false});
const backup=e.exportEncrypted();
assert(!backup.includes('Private voice samples'));
assert.equal(e.getBuyer('NewBuyer123').settings.personality,'sweet');
assert(!backup.includes('First private message'),'Plaintext found in encrypted blob');
const importStorage=new Map();const imported=new EncryptedVault({getItem:k=>importStorage.get(k)||null,setItem:(k,v)=>importStorage.set(k,v),removeItem:k=>importStorage.delete(k)});
await imported.importEncrypted(backup);await imported.unlock('unit-test-secret-passphrase');
assert.equal(imported.getReferences()[0].text,'Private voice samples');
assert.equal(imported.getBuyer('julianr9423').settings.personality,'spicy');
const other=new EncryptedVault(localStorage);
await assert.rejects(other.unlock('wrong-passphrase'),/Could not unlock/);
await other.unlock('unit-test-secret-passphrase');
assert.equal(other.getBuyer('julianr9423').events[0].content,'First private message');
assert.equal(other.getReferences()[0].text,'Private voice samples');
assert.equal(other.getBuyer('julianr9423').settings.personality,'spicy');
assert.equal(other.getBuyer('julianr9423').settings.smartSelect,true);
assert.equal(other.getBuyer('NewBuyer123').settings.smartSelect,false);
await other.setReferences([]);assert.equal(other.getReferences().length,0);
await other.removeBuyer('julianr9423');
assert.equal(other.list().length,1);
await other.ensureBuyer('ExpiredBuyer123');
await other.addIncoming('ExpiredBuyer123','Old chat from prior month');
await other.update(d=>{const old=d.buyers.find(b=>b.username==='expiredbuyer123');old.lastMessageAt=Date.now()-31*86400000;});
await other.setBuyerNotes('ExpiredBuyer123','Notes should not extend conversation retention');
const expired=await other.pruneInactive(30,Date.now());
assert.equal(expired,1);
assert.equal(other.getBuyer('ExpiredBuyer123'),null);
assert.equal(other.getBuyer('NewBuyer123').events.length,1);
console.log('PASS: AES-GCM vault, buyer isolation, persisted settings, individual deletion, and 30-day inactive-chat cleanup');
